import { execFileSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CATALOG_FILE = "src/core/failures/catalog.js";
const REGISTRY_FILE = "src/twins/registry.js";
const LOADER_FILE = "src/core/scenarios/loader.js";
const DATA_FILES = [
  "src/twins/flutterwave/data/account-names.json",
  "src/twins/flutterwave/data/banks.json",
  "src/twins/paystack/data/account-names.json",
  "src/twins/paystack/data/banks.json",
];
const ASSUMED_LABEL = "Assumed: not confirmed by the service's documentation.";

function quote(value) {
  return `\`${String(value)}\``;
}

function typeLabel(schema) {
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => quote(value)).join(" or ");
  }

  if (Array.isArray(schema.anyOf)) {
    const nullable = schema.anyOf.some((part) => part.type === "null");
    const parts = schema.anyOf.filter((part) => part.type !== "null");
    if (parts.length === 1) {
      return `${typeLabel(parts[0])}${nullable ? ", or empty" : ""}`;
    }
    return parts.map((part) => typeLabel(part)).join(" or ");
  }

  switch (schema.type) {
    case "integer":
      return "Whole number";
    case "number":
      return "Number";
    case "boolean":
      return "True or false";
    case "string":
      return schema.minLength === undefined ? "Text" : "Text with at least one character";
    default:
      return "Value";
  }
}

function allowedLabel(schema) {
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => quote(value)).join(" or ");
  }

  if (Array.isArray(schema.anyOf)) {
    const nullable = schema.anyOf.some((part) => part.type === "null");
    const parts = schema.anyOf.filter((part) => part.type !== "null");
    const base = parts.map((part) => allowedLabel(part)).join(" or ");
    return nullable ? `${base}, or empty` : base;
  }

  if (schema.minimum !== undefined && schema.maximum !== undefined) {
    return `${schema.minimum} to ${schema.maximum}`;
  }

  return "Any valid value";
}

function defaultLabel(schema) {
  if (schema.default === null) {
    return "Empty";
  }
  if (schema.default === undefined) {
    return "No default";
  }
  return quote(schema.default);
}

function settingRows(failure) {
  const properties = failure.settingsJsonSchema.properties ?? {};
  const rows = [];

  for (const [name, schema] of Object.entries(properties)) {
    if (name === "twins" || name === "actions") {
      continue;
    }
    rows.push(
      `| ${quote(name)} | ${typeLabel(schema)} | ${allowedLabel(schema)} | ${defaultLabel(schema)} |`,
    );
  }

  return rows;
}

function failureSupportLines(failure, definitions) {
  const lines = [];

  for (const definition of definitions) {
    const support = definition.failures.support.find((item) => item.id === failure.id);
    if (support === undefined) {
      continue;
    }

    if (support.source === "assumed") {
      const reference =
        support.sourceReference === undefined ? "" : ` Reference: ${support.sourceReference}`;
      lines.push(`- **${definition.displayName}**: ${ASSUMED_LABEL}${reference}`);
    } else if (support.source === "real-story") {
      const reference =
        support.sourceReference === undefined
          ? "No entry reference is recorded."
          : `STORIES.md entry: ${support.sourceReference}.`;
      lines.push(`- **${definition.displayName}**: Real story. ${reference}`);
    } else {
      const reference =
        support.sourceReference === undefined
          ? "No research section is recorded."
          : support.sourceReference;
      lines.push(`- **${definition.displayName}**: Docs. Reference: ${reference}.`);
    }
  }

  if (lines.length === 0) {
    lines.push("- No registered twin supports this failure in version 0.1.0.");
  }

  return lines;
}

function renderFailures(catalog, definitions) {
  const lines = [
    "# Failure library",
    "",
    "This file is generated by `scripts/generate-docs.mjs` from the failure catalog and the twin definitions. Do not edit it by hand.",
    "",
    "Each failure below shows what happens in real life, what to check in your app, its settings, and the twins that support it.",
    "",
  ];

  for (const failure of catalog) {
    lines.push(`## ${failure.name}`, "");
    lines.push(`When this happens in real life: ${failure.description.realLife}`, "");
    lines.push(`What to check in your app: ${failure.description.whatToCheck}`, "");
    lines.push("Settings:", "");
    lines.push("| Setting | Type | Allowed | Default |");
    lines.push("| --- | --- | --- | --- |");
    lines.push(...settingRows(failure));
    lines.push("");

    if (failure.id === "server-error" || failure.id === "rate-limited") {
      lines.push(
        "An empty `times` value means the failure fires every time while the rule is on.",
        "",
      );
    }

    lines.push("Applies to:", "");
    lines.push(...failureSupportLines(failure, definitions));
    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

function formatValue(value) {
  if (value === null) {
    return "empty";
  }
  if (typeof value === "string") {
    return quote(value);
  }
  if (typeof value === "number" || typeof value === "boolean") {
    return quote(value);
  }
  if (Array.isArray(value)) {
    return value.map((item) => formatValue(item)).join(", ");
  }
  return quote(JSON.stringify(value));
}

function formatSettings(settings) {
  const entries = Object.entries(settings);
  if (entries.length === 0) {
    return "the defaults";
  }
  return entries.map(([name, value]) => `${quote(name)}: ${formatValue(value)}`).join(", ");
}

function formatActions(rule) {
  if (rule.actions === undefined) {
    return "every action the failure applies to";
  }
  const actions = typeof rule.actions === "string" ? [rule.actions] : rule.actions;
  return actions.map((action) => quote(action)).join(", ");
}

function twinsSentence(twinIds, definitions) {
  const names = twinIds.map((id) => {
    const definition = definitions.find((item) => item.id === id);
    return definition === undefined ? id : definition.displayName;
  });

  if (names.length === 0) {
    return "No twins are listed.";
  }
  if (names.length === 1) {
    return names[0];
  }
  if (names.length === 2) {
    return `${names[0]} and ${names[1]}`;
  }
  return `${names.slice(0, -1).join(", ")}, and ${names.at(-1)}`;
}

function renderScenarios(scenarios, catalog, definitions) {
  const lines = [
    "# Scenarios",
    "",
    "This file is generated by `scripts/generate-docs.mjs` from the scenario files and the failure catalog. Do not edit it by hand.",
    "",
    "A scenario switches on a named set of failure rules. Run it from the dashboard, the CLI, or the control API.",
    "",
  ];

  for (const scenario of scenarios) {
    const failureById = new Map(catalog.map((failure) => [failure.id, failure]));
    lines.push(`## ${scenario.name}`, "");
    lines.push(`Id: ${quote(scenario.id)}`, "");
    lines.push(scenario.story, "");
    lines.push(`Twins: ${twinsSentence(scenario.twins, definitions)}.`, "");
    lines.push("Rules:", "");

    for (const rule of scenario.rules) {
      const failure = failureById.get(rule.failureId);
      const name = failure === undefined ? rule.failureId : failure.name;
      lines.push(
        `- ${name} (${quote(rule.failureId)}) on ${formatActions(rule)} with ${formatSettings(rule.settings)}.`,
      );
    }

    if (scenario.steps.length > 0) {
      lines.push("", "Steps:", "");
      for (const step of scenario.steps) {
        lines.push(
          `- After ${step.afterSeconds} seconds, remove the rule ${quote(step.removeRule)}.`,
        );
      }
    }

    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

async function copyDataFiles(output) {
  for (const file of DATA_FILES) {
    const target = join(output, file);
    await mkdir(dirname(target), { recursive: true });
    await copyFile(join(ROOT, file), target);
  }
}

async function compileProject() {
  const output = await mkdtemp(join(ROOT, ".tmp-docs-"));

  try {
    execFileSync(
      process.execPath,
      [
        join(ROOT, "node_modules/typescript/bin/tsc"),
        "-p",
        join(ROOT, "tsconfig.json"),
        "--noEmit",
        "false",
        "--outDir",
        output,
        "--declaration",
        "false",
        "--sourceMap",
        "false",
      ],
      { cwd: ROOT, encoding: "utf8", stdio: "pipe" },
    );
    await copyDataFiles(output);
    return output;
  } catch (error) {
    await rm(output, { recursive: true, force: true });
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`The docs build could not compile the project.\n${detail}`, { cause: error });
  }
}

async function generate() {
  const output = await compileProject();

  try {
    const { FAILURE_CATALOG } = await import(pathToFileURL(join(output, CATALOG_FILE)).href);
    const { registry } = await import(pathToFileURL(join(output, REGISTRY_FILE)).href);
    const { loadScenarios } = await import(pathToFileURL(join(output, LOADER_FILE)).href);
    const definitions = registry.list();
    const scenarios = await loadScenarios(join(ROOT, "scenarios"));

    return {
      failures: renderFailures(FAILURE_CATALOG, definitions),
      scenarios: renderScenarios(scenarios, FAILURE_CATALOG, definitions),
    };
  } finally {
    await rm(output, { recursive: true, force: true });
  }
}

async function main() {
  const generated = await generate();
  const check = process.argv.includes("--check");
  const files = [
    { path: join(ROOT, "docs/failures.md"), content: generated.failures },
    { path: join(ROOT, "docs/scenarios.md"), content: generated.scenarios },
  ];

  if (check) {
    let stale = false;
    for (const file of files) {
      let committed;
      try {
        committed = await readFile(file.path, "utf8");
      } catch {
        stale = true;
        console.error(`${file.path} is missing. Run node scripts/generate-docs.mjs.`);
        continue;
      }
      if (committed !== file.content) {
        stale = true;
        console.error(`${file.path} is out of date. Run node scripts/generate-docs.mjs.`);
      }
    }

    if (stale) {
      process.exitCode = 1;
      return;
    }
    console.log("Docs match the failure catalog and scenario files.");
    return;
  }

  for (const file of files) {
    await writeFile(file.path, file.content);
  }
  console.log("Wrote docs/failures.md and docs/scenarios.md.");
}

await main();
